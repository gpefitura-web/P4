"""Verifica o estilo do manuscrito e a ausência de marcas de IA nas pastas públicas.

Regras (kit.yml, bloco 'verificacao'; padrões abaixo valem se o bloco faltar):
  travessao, ponto_virgula, hifen_pontuacao: true/false, estilo de prosa (origem: DEC-21/31 do P1)
  marcas_ia: true/false e marcas_ia_regex: política DEC-02 do P1, a depender da revista (REG-IA)
  pastas_publicas: pastas varridas em busca de marcas de IA (padrão manuscrito e repositorio)
  extra: lista de módulos em kit/pipeline/hooks/ com função check(root) -> list[str]

Na prosa dos arquivos .tex de manuscrito/ (fora de template/) procura: travessões (em dash, en dash e os
traços duplos e triplos do LaTeX), ponto e vírgula, e hífen entre espaços usado como pontuação.
Matemática, comentários, argumentos de comandos de referência e URLs ficam de fora.
Procura também marcas de ferramentas de IA em todos os arquivos de texto de manuscrito/ e repositorio/.

Uso: python3 scripts/check_manuscript.py [pasta_do_manuscrito]
Sai com código 1 se achar algo.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MS = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "manuscrito"

DEFAULT_AI = r"(?i)\b(claude|anthropic|chatgpt|openai|gpt-?[0-9]|llm|language model|co-authored-by|generated by)\b"
try:
    import yaml
    CFG = (yaml.safe_load((ROOT / "kit.yml").read_text(encoding="utf-8")) or {}).get("verificacao", {}) or {}
except Exception:
    CFG = {}
AI_MARKS = re.compile(CFG.get("marcas_ia_regex", DEFAULT_AI))
RULES = {k: CFG.get(k, True) for k in ("travessao", "ponto_virgula", "hifen_pontuacao", "marcas_ia")}
PUBLIC = [ROOT / p for p in CFG.get("pastas_publicas", ["manuscrito", "repositorio"])]
TEXT_EXT = {".tex", ".bib", ".md", ".py", ".txt", ".json", ".sty", ".cls", ".bst", ".yml", ".sh"}

MATH = [
    re.compile(r"\$\$.*?\$\$", re.S),
    re.compile(r"\$[^$\n]*\$"),
    re.compile(r"\\\[.*?\\\]", re.S),
    re.compile(r"\\\(.*?\\\)", re.S),
    re.compile(r"\\begin\{(equation|align|eqnarray|gather|multline|displaymath|verbatim|lstlisting)\*?\}.*?\\end\{\1\*?\}", re.S),
]
ARGS = re.compile(r"\\(cite[a-zA-Z]*|ref|eqref|label|includegraphics|input|include|url|href|bibliography|bibliographystyle|"
                  r"usepackage|documentclass|graphicspath|pageref|autoref)\*?(\[[^\]]*\])*\{[^}]*\}")


def rel(path):
    try:
        return path.relative_to(ROOT)
    except ValueError:
        return path


def strip_comments(text):
    return re.sub(r"(?m)(?<!\\)%.*$", "", text)


def prose_lines(path):
    text = strip_comments(path.read_text(encoding="utf-8", errors="ignore"))
    for rx in MATH:
        text = rx.sub(lambda m: re.sub(r"[^\n]", " ", m.group(0)), text)
    text = ARGS.sub(lambda m: " " * len(m.group(0)), text)
    return text.split("\n")


def main():
    problems = []
    if MS.exists():
        for p in sorted(MS.rglob("*.tex")):
            if "template" in p.parts or p.name in {"journal_macros.tex", "results_macros.tex"}:
                continue
            for n, line in enumerate(prose_lines(p), 1):
                if RULES["travessao"] and (re.search("[\u2013\u2014]", line) or "---" in line or "--" in line):
                    problems.append(f"{rel(p)}:{n}: travessao ou traco duplo na prosa")
                if RULES["ponto_virgula"] and ";" in line:
                    problems.append(f"{rel(p)}:{n}: ponto e virgula na prosa")
                if RULES["hifen_pontuacao"] and re.search(r"\s-\s", line):
                    problems.append(f"{rel(p)}:{n}: hifen entre espacos usado como pontuacao")
    for base in (PUBLIC if RULES["marcas_ia"] else []):
        if not base.exists():
            continue
        for p in sorted(base.rglob("*")):
            if (not p.is_file() or p.suffix.lower() not in TEXT_EXT or "template" in p.parts or "fonts" in p.parts
                    or p.name.startswith("ESPECIFICACAO") or p.name == "kit.yml"):
                continue
            for n, line in enumerate(p.read_text(encoding="utf-8", errors="ignore").split("\n"), 1):
                if p.suffix == ".py" and "AI_MARKS" in line:
                    continue
                if AI_MARKS.search(line):
                    problems.append(f"{rel(p)}:{n}: possivel marca de IA: {AI_MARKS.search(line).group(0)}")
    for name in CFG.get("extra", []) or []:
        try:
            import importlib.util
            spec = importlib.util.spec_from_file_location(name, ROOT / "kit" / "pipeline" / "hooks" / f"{name}.py")
            mod = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(mod)
            problems.extend(mod.check(ROOT))
        except Exception as exc:
            problems.append(f"hook {name} falhou: {exc}")
    for q in problems:
        print(q)
    print(f"{len(problems)} problema(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
